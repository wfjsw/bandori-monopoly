thread_local! {
    /// The run currently executing, boxed so its address is stable: a nested
    /// `play_card` swaps in its own host and the outer reference stays valid.
    static HOST: std::cell::RefCell<Option<Box<dyn HostOps>>> = const { std::cell::RefCell::new(None) };
}

/// Install the host a card run executes against. Returns the previous one, so
/// a nested card call can restore its caller's host when it returns.
pub fn install_host(h: Box<dyn HostOps>) -> Option<Box<dyn HostOps>> {
    HOST.with(|slot| slot.borrow_mut().replace(h))
}

/// Drop the installed host (end of the outermost card call).
pub fn take_host() -> Option<Box<dyn HostOps>> {
    HOST.with(|slot| slot.borrow_mut().take())
}

pub(crate) fn with_host<T>(f: impl FnOnce(&mut dyn HostOps) -> T) -> T {
    // Borrow only long enough to take a stable pointer -- a nested `run_on`
    // replaces the slot while `f` is on the stack, so holding the `RefCell`
    // borrow across `f` would be `already borrowed`.
    let ptr: *mut dyn HostOps = HOST.with(|h| {
        let mut slot = h.borrow_mut();
        let b = slot.as_mut().expect("rules-native host not installed");
        &mut **b as *mut dyn HostOps
    });
    // SAFETY: the host is boxed, so the pointee does not move when a nested
    // run swaps the slot; it is only dropped after `run_on` restores the
    // outer box, which happens after `f` returns (or unwinds).
    f(unsafe { &mut *ptr })
}

/// A host import aborted the run. The panic payload is the [`HostErr`]; the
/// embedder's `catch_unwind` folds it back into the trap contract.
pub fn abort_host(e: HostErr) -> ! {
    std::panic::panic_any(e)
}

