#!/usr/bin/env python3
"""Generate `rules/kani/src/generated/body_dispatch_arms.rs`.

One match arm per RULESET index. Each arm feeds a `&'static CardDef`
constant into `invoke::call_body` (inline(always)) so the `fn(i32) ->
Asked` load is a constant address and LLVM emits a **direct** call.

Why: a single shared `code*` call site makes CBMC's function-pointer
removal expand an IF-chain over every address-taken function in the
binary (~4300 targets in the events unit). That chain is the SAT cliff
(`duobang_01_02_two_player_iff` 680 s → TIMEOUT on the batch-2 invoke
rewrite). Per-card call sites keep each site 1-target.

Band lengths are pinned to `invoke::BAND_START` (verified by
`band_starts_match_ruleset` / `conf_hostops2`).

Regenerate after adding a card / skill / event / tile / mark:

    python3 tools/kani/gen_body_dispatch.py
"""

from __future__ import annotations

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
INVOKE = ROOT / "rules/kani/src/invoke.rs"
OUT = ROOT / "rules/kani/src/generated/body_dispatch_fn.rs"

# (rust crate ident, base index, count) — must match invoke::RULESET order
# and BAND_START. The script re-reads BAND_START to stay in lockstep.
BANDS = [
    ("card_ag", 0, 15),
    ("card_crychic", 15, 15),
    ("card_general", 30, 14),
    ("card_hhw", 44, 15),
    ("card_morfonica", 59, 15),
    ("card_mujica", 74, 15),
    ("card_mygo", 89, 15),
    ("card_pp", 104, 19),
    ("card_ppp", 123, 18),
    ("card_ras", 141, 15),
    ("card_roselia", 156, 17),
    ("card_sumimi", 173, 11),
    ("skill_bands", 184, 12),
    ("skill_characters", 196, 54),
    ("rules_tiles", 250, 6),
    ("rules_tile_marks", 256, 1),
    ("rules_events", 257, 28),
]


def band_start_from_invoke() -> list[int]:
    text = INVOKE.read_text()
    m = re.search(
        r"pub const BAND_START: \[usize; 18\] = \[([^\]]+)\]", text, re.S
    )
    if not m:
        sys.exit("BAND_START not found in invoke.rs")
    nums = [int(x.strip()) for x in m.group(1).split(",") if x.strip()]
    if len(nums) != 18:
        sys.exit(f"BAND_START must have 18 entries, got {len(nums)}")
    return nums


def main() -> None:
    starts = band_start_from_invoke()
    # Recompute (base, count) from BAND_START so a table edit cannot drift.
    computed = []
    for i, (crate, _base, _n) in enumerate(BANDS):
        base = starts[i]
        count = starts[i + 1] - starts[i]
        computed.append((crate, base, count))
    if starts[-1] != 285:
        sys.exit(f"CARD_COUNT drift: BAND_START end is {starts[-1]}, expected 285")

    lines: list[str] = []
    # Full `call_body_idx` item (included at item position in invoke.rs).
    # `include!` is a pattern macro inside `match`, so the match cannot live
    # in invoke.rs — generate the whole function.
    lines.append("// GENERATED by tools/kani/gen_body_dispatch.py — do not edit.")
    lines.append("// Per-card body dispatch for Kani. Regenerate:")
    lines.append("//   python3 tools/kani/gen_body_dispatch.py")
    lines.append("")
    lines.append("/// Per-card body dispatch (Kani). One match arm per `RULESET` index,")
    lines.append("/// each a direct `call_body` on a `&'static` constant.")
    lines.append("#[cfg(kani)]")
    lines.append("fn call_body_idx(idx: usize, entry_index: usize, player: i32) -> Asked {")
    lines.append("    match idx {")
    for crate, base, count in computed:
        if count <= 0:
            sys.exit(f"empty band {crate} at {base}")
        for off in range(count):
            idx = base + off
            lines.append(
                f"        {idx} => call_body(&{crate}::CARDS[{off}], entry_index, player),"
            )
    lines.append("        _ => fail_unknown_idx(idx),")
    lines.append("    }")
    lines.append("}")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({sum(c for _, _, c in computed)} arms)")


if __name__ == "__main__":
    main()