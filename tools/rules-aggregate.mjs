#!/usr/bin/env node
// Generate `rules/cards/card-all`: the single wasm module we ship.
//
// The *source* stays one crate per band and one .rs per card -- that layout is
// for authors. Only the artifact is unified: every band crate compiles to an
// rlib that `card-all` links, so the SDK/std floor is built once instead of
// once per band (the floor is most of each module, so this is an order of
// magnitude).
//
// `tools/build-ruleset.mjs` runs this first, so adding or removing a band crate
// needs no manual bookkeeping. The output is deterministic -- safe to commit.
//
// Usage: node tools/rules-aggregate.mjs

import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const CARDS = join(ROOT, "rules", "cards");
const OUT = join(CARDS, "card-all");

/** [{dir, name}] of every band crate, sorted. */
function bandCrates() {
  return readdirSync(CARDS, { withFileTypes: true })
    .filter((e) => e.isDirectory() && e.name !== "card-all")
    .map((e) => e.name)
    .sort()
    .flatMap((dir) => {
      const toml = join(CARDS, dir, "Cargo.toml");
      const m = readFileSync(toml, "utf8").match(/^name = "([^"]+)"/m);
      if (!m) throw new Error(`${toml}: no package name`);
      return [{ dir, name: m[1] }];
    });
}

const crates = bandCrates();
if (!crates.length) {
  console.error("no band crates found");
  process.exit(1);
}

const deps = crates.map((c) => `${c.name} = { path = "../${c.dir}" }`).join("\n");
const tables = crates.map((c) => `    ${c.name.replaceAll("-", "_")}::CARDS`).join(",\n");

mkdirSync(join(OUT, "src"), { recursive: true });
writeFileSync(join(OUT, "Cargo.toml"), `[package]
name = "card-all"
version = "0.1.0"
edition = "2021"
license = "MIT"
description = "The shipped ruleset: every band's cards in one wasm module."

# The only cdylib of the card set. The band crates are rlibs it links.
[lib]
crate-type = ["cdylib"]

[dependencies]
card-sdk = { path = "../../card-sdk", features = ["guest"] }
${deps}

# generated by tools/rules-aggregate.mjs -- do not edit; rerun that instead
`);

writeFileSync(join(OUT, "src", "lib.rs"), `//! The shipped card ruleset: every band's table in one module.
//!
//! Generated by \`tools/rules-aggregate.mjs\` -- do not edit. The band crates
//! stay one-per-band (and one .rs per card) for authors; unifying the
//! *artifact* keeps the SDK and allocator linked once instead of once per
//! band, which is most of the size of a module.

#![cfg_attr(target_arch = "wasm32", no_std)]

card_sdk::bandori_ruleset!(
${tables}
);
`);

console.log(`card-all: ${crates.length} band crates linked`);
for (const c of crates) console.log(`  ${c.name} <- rules/cards/${c.dir}`);