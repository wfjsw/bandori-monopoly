#!/usr/bin/env node
// Lift roster metadata into the Rust rule sources (ABI v63, docs/CARDS.md
// 「Card metadata」). The lift is **complete** -- the Rust code is the single
// source -- and this tool now reads the generated fixture
// (`crates/game-core/tests/fixtures/roster.json`) as its row table, so a
// re-lift / tweak is still possible without the retired `data/*.json` files.
//
// Per-band runs touch only that band's files, so they are safe to run
// concurrently across bands. The shared ordinal table is written once
// (idempotent, atomic) and never by a `--band` run.
//
// Usage:
//   node tools/lift-roster.mjs --ordinals          # generate roster_order.rs only
//   node tools/lift-roster.mjs --band Sumimi       # lift one band crate + its skills
//   node tools/lift-roster.mjs --card 通用:GREAT    # lift one card outside band mode
//   node tools/lift-roster.mjs --tables            # rebuild BANDS/CHARACTERS tables
//   node tools/lift-roster.mjs --all               # every band + general + tables
//
// Idempotent: re-running makes no change when the sources already match.

import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const CARDS = join(ROOT, "rules", "cards");
const SKILL_C = join(ROOT, "rules", "skills", "skill-characters");
const SKILL_B = join(ROOT, "rules", "skills", "skill-bands");
const ORDER_RS = join(ROOT, "rules", "ruleset-core", "src", "roster_order.rs");
const FIXTURE = join(ROOT, "crates", "game-core", "tests", "fixtures", "roster.json");

const fixture = JSON.parse(readFileSync(FIXTURE, "utf8"));
const cards = fixture.cards;
const characters = fixture.characters;
const bands = fixture.bands;

// ---------------------------------------------------------------------------
// Ordinal tables (shared, generated once)
// ---------------------------------------------------------------------------

function ordinalsSource() {
  const fmt = (name, pairs) => {
    const lines = [`pub const ${name}: &[(&str, i32)] = &[`];
    for (const [k, o] of pairs) {
      lines.push(`    (${rustString(k)}, ${o}),`);
    }
    lines.push("];");
    return lines.join("\n");
  };
  return `//! Canonical roster order: the Rust ordinal table (fixture / metadata dump order).
//!
//! Generated by \`tools/lift-roster.mjs\` -- do not edit by hand. The ruleset
//! registers cards alphabetically inside each band crate, so the metadata
//! export sorts by these ordinals to rebuild the exact JSON order the deck
//! builder and presets depend on. One shared table (not per-band) so
//! concurrent per-band lift runs never write the same file twice.

${fmt("CARDS", cards.map((c) => [c.id, cards.indexOf(c)]))}

${fmt("CHARACTERS", characters.map((c) => [c.name, characters.indexOf(c)]))}

${fmt("BANDS", bands.map((b) => [b.name, bands.indexOf(b)]))}
`;
}

function writeIfChanged(path, text) {
  const prev = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (prev === text) return false;
  writeFileSync(path, text);
  return true;
}

function liftOrdinals() {
  const changed = writeIfChanged(ORDER_RS, ordinalsSource());
  console.log(changed ? `wrote ${ORDER_RS}` : `up to date ${ORDER_RS}`);
}

// ---------------------------------------------------------------------------
// Rust string literals (byte-exact: raw strings keep newlines / CJK / spaces)
// ---------------------------------------------------------------------------

function rustString(s) {
  if (s === "") return '""';
  // Prefer a raw string; bump hashes until the body cannot terminate it.
  for (let n = 1; n < 20; n++) {
    const h = "#".repeat(n);
    const open = `r${h}"`;
    const close = `"${h}`;
    if (!s.includes(close)) return `${open}${s}${close}`;
  }
  // Fallback: escaped normal string (lossless for any content).
  return JSON.stringify(s);
}

function rustStrArray(arr) {
  if (!arr.length) return "&[]";
  return `&[${arr.map(rustString).join(", ")}]`;
}

