function rebuildTables() {
  // Collect CHARACTER consts from skill-characters, BAND consts from skill-bands.
  const charConsts = [];
  for (const f of readdirSync(join(SKILL_C, "src")).sort()) {
    if (!f.endsWith(".rs") || f === "lib.rs" || f === "roster_table.rs") continue;
    const text = readFileSync(join(SKILL_C, "src", f), "utf8");
    if (/pub const CHARACTER:/.test(text)) {
      const mod = f.replace(/\.rs$/, "");
      charConsts.push(mod);
    }
  }
  const bandConsts = [];
  for (const f of readdirSync(join(SKILL_B, "src")).sort()) {
    if (!f.endsWith(".rs") || f === "lib.rs" || f === "roster_table.rs") continue;
    const text = readFileSync(join(SKILL_B, "src", f), "utf8");
    if (/pub const BAND:/.test(text)) {
      const mod = f.replace(/\.rs$/, "");
      bandConsts.push(mod);
    }
  }

  const charTable = [
    "//! Generated by `tools/lift-roster.mjs --tables` -- the character",
    "//! metadata rows defined beside each skill rule. Rebuild after lifting a band.",
    "",
    "use alloc::vec::Vec;",
    "use card_sdk::meta::MetaRow;",
    "use ruleset_core::roster::CharacterDef;",
    "",
    ...charConsts.map((m) => `pub use super::${m}::CHARACTER as ${m.toUpperCase().replace(/[^A-Z0-9]/g, "_")};`),
    "",
    "/// Every lifted character, in skill-file order (the export sorts by ordinal).",
    "pub const CHARACTERS: &[CharacterDef] = &[",
    ...charConsts.map((m) => `    ${m.toUpperCase().replace(/[^A-Z0-9]/g, "_")},`),
    "];",
    "",
    "/// Wire rows for `bandori_metadata`.",
    "pub fn meta_rows() -> Vec<MetaRow> {",
    "    card_sdk::meta::rows_of(CHARACTERS)",
    "}",
    "",
  ].join("\n");

  const bandTable = [
    "//! Generated by `tools/lift-roster.mjs --tables` -- the band",
    "//! metadata rows defined beside each band-skill rule. Rebuild after lifting a band.",
    "",
    "use alloc::vec::Vec;",
    "use card_sdk::meta::MetaRow;",
    "use ruleset_core::roster::BandDef;",
    "",
    ...bandConsts.map((m) => `pub use super::${m}::BAND as ${m.toUpperCase().replace(/[^A-Z0-9]/g, "_")};`),
    "",
    "/// Every lifted band, in skill-file order (the export sorts by ordinal).",
    "pub const BANDS: &[BandDef] = &[",
    ...bandConsts.map((m) => `    ${m.toUpperCase().replace(/[^A-Z0-9]/g, "_")},`),
    "];",
    "",
    "/// Wire rows for `bandori_metadata`.",
    "pub fn meta_rows() -> Vec<MetaRow> {",
    "    card_sdk::meta::rows_of(BANDS)",
    "}",
    "",
  ].join("\n");

  // Ensure lib.rs exposes the table module.
  ensureLibModule(join(SKILL_C, "src", "lib.rs"), "roster_table");
  ensureLibModule(join(SKILL_B, "src", "lib.rs"), "roster_table");

  const c = writeIfChanged(join(SKILL_C, "src", "roster_table.rs"), charTable);
  const b = writeIfChanged(join(SKILL_B, "src", "roster_table.rs"), bandTable);
  console.log(`character table: ${charConsts.length} def(s)${c ? " (updated)" : ""}`);
  console.log(`band table: ${bandConsts.length} def(s)${b ? " (updated)" : ""}`);
}

function ensureLibModule(libPath, mod) {
  let src = readFileSync(libPath, "utf8");
  if (src.includes(`pub mod ${mod};`)) return;
  // Insert after the last `pub mod` / `use` line near the top.
  const lines = src.split("\n");
  let at = 0;
  for (let i = 0; i < lines.length; i++) {
    if (/^pub mod |^use |^pub use /.test(lines[i])) at = i + 1;
  }
  lines.splice(at, 0, `pub mod ${mod};`);
  writeFileSync(libPath, lines.join("\n"));
}

