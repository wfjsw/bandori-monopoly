function crateForBand(bandName) {
  // JSON band name -> crate directory. `通用` is the general-card band (not in
  // the roster); `CiRCLE` is a real band whose exclusive cards live in
  // `card-general` (band field `通用`), so it has no card crate of its own.
  const map = {
    "Poppin' Party": "card-ppp",
    Afterglow: "card-ag",
    "Pastel✽Palettes": "card-pp",
    Roselia: "card-roselia",
    "Hello, Happy World!": "card-hhw",
    Morfonica: "card-morfonica",
    "RAISE A SUILEN": "card-ras",
    "MyGO!!!!!": "card-mygo",
    "Ave Mujica": "card-mujica",
    Sumimi: "card-sumimi",
    CRYCHIC: "card-crychic",
    "通用": "card-general",
  };
  return map[bandName];
}

function liftBandCards(bandName) {
  const crate = crateForBand(bandName);
  const rows = new Map(cards.filter((c) => c.band === bandName).map((c) => [c.id, c]));
  if (!crate) {
    // No card crate (e.g. CiRCLE). Its exclusive cards are `通用:*` rows and
    // are lifted by the general pass; a band with rows but no crate is a bug.
    if (rows.size) {
      throw new Error(
        `no crate mapping for band ${bandName} (${rows.size} card(s): ${[...rows.keys()].join(", ")})`,
      );
    }
    return 0;
  }
  const dir = join(CARDS, crate, "src");
  let n = 0;
  for (const f of readdirSync(dir)) {
    if (!f.endsWith(".rs")) continue;
    const path = join(dir, f);
    if (replaceMetaInFile(path, rows)) {
      const defs = findCardDefs(readFileSync(path, "utf8")).filter((d) => rows.has(d.id));
      n += defs.length;
      console.log(`meta: ${crate}/${f} (${defs.length} card(s))`);
    }
  }
  // Verify every card of this band was found.
  const found = new Set();
  for (const f of readdirSync(dir)) {
    if (!f.endsWith(".rs")) continue;
    for (const d of findCardDefs(readFileSync(join(dir, f), "utf8"))) {
      if (rows.has(d.id)) found.add(d.id);
    }
  }
  const missing = [...rows.keys()].filter((id) => !found.has(id));
  if (missing.length) {
    console.warn(`WARNING: ${bandName}: CardDef not found for ${missing.join(", ")}`);
  }
  return found.size;
}

function liftCard(id) {
  const row = cards.find((c) => c.id === id);
  if (!row) throw new Error(`no roster card row for ${id}`);
  const crate = crateForBand(row.band);
  if (!crate) throw new Error(`no crate mapping for band ${row.band} (card ${id})`);
  const dir = join(CARDS, crate, "src");
  const rows = new Map([[id, row]]);
  let hit = false;
  for (const f of readdirSync(dir)) {
    if (!f.endsWith(".rs")) continue;
    if (replaceMetaInFile(join(dir, f), rows)) {
      console.log(`meta: ${crate}/${f} (card ${id})`);
      hit = true;
    }
  }
  if (!hit) {
    // Maybe already up to date.
    for (const f of readdirSync(dir)) {
      if (!f.endsWith(".rs")) continue;
      const defs = findCardDefs(readFileSync(join(dir, f), "utf8"));
      if (defs.some((d) => d.id === id)) return;
    }
    throw new Error(`CardDef not found for ${id} in ${crate}`);
  }
}

function liftBandSkills(bandName) {
  // Band def beside the band skill.
  const b = bands.find((x) => x.name === bandName);
  if (b && b.skill) {
    const id = `skill:${b.name}:${b.skill}`;
    const file = findSkillFile(SKILL_B, id);
    if (file) {
      const doc = `/// Roster band row for this band skill (ABI v63).\n`;
      const ch = upsertConst(file, BAND_CONST, bandDefCall(b), doc);
      console.log(`${ch ? "wrote" : "up to date"} BandDef in ${file}`);
    } else if (b.name !== "通用") {
      console.warn(`WARNING: no skill-bands file for ${id}`);
    }
  }
  // Character defs beside each character skill of this band.
  for (const c of characters.filter((x) => x.band === bandName)) {
    if (!c.skill) continue;
    const id = `skill:${c.name}:${c.skill}`;
    const file = findSkillFile(SKILL_C, id);
    if (file) {
      const doc = `/// Roster character row for this skill's owner (ABI v63).\n`;
      const ch = upsertConst(file, CHARACTER_CONST, characterDefCall(c), doc);
      console.log(`${ch ? "wrote" : "up to date"} CharacterDef (${c.name}) in ${file}`);
    } else {
      console.warn(`WARNING: no skill-characters file for ${id}`);
    }
  }
}

function main() {
  const args = process.argv.slice(2);
  const get = (flag) => {
    const i = args.indexOf(flag);
    return i >= 0 ? args[i + 1] : null;
  };
  const has = (flag) => args.includes(flag);

  if (!args.length || has("--ordinals") || has("--all")) liftOrdinals();

  const band = get("--band");
  if (band) {
    liftBandCards(band);
    liftBandSkills(band);
  }

  const card = get("--card");
  if (card) liftCard(card);

  if (has("--all")) {
    // Every band row, then the general-card band (`通用`, not a band).
    // Tables rebuild after the lifts so new CHARACTER / BAND consts are
    // collected on the same run.
    for (const b of bands) {
      liftBandCards(b.name);
      liftBandSkills(b.name);
    }
    liftBandCards("通用");
  }

  if (has("--tables") || has("--all")) rebuildTables();

  if (!args.length) {
    // Default: ordinals only, and remind about the rest.
    console.log("hint: --band Sumimi | --card <id> | --tables | --all");
  }
}

main();