/** Advance `i` past Rust whitespace + comments. Returns the new index. */
function skipTrivia(src, i) {
  while (i < src.length) {
    if (/\s/.test(src[i])) {
      i++;
    } else if (src.startsWith("//", i)) {
      // Line comment (but not a raw string opener we mishandle -- `//` is fine).
      while (i < src.length && src[i] !== "\n") i++;
    } else if (src.startsWith("/*", i)) {
      let depth = 1;
      i += 2;
      while (i < src.length && depth > 0) {
        if (src.startsWith("/*", i)) {
          depth++;
          i += 2;
        } else if (src.startsWith("*/", i)) {
          depth--;
          i += 2;
        } else i++;
      }
    } else break;
  }
  return i;
}

/** Scan one Rust token starting at `i` (string / char / comment / paren / word). */
function scanToken(src, i) {
  if (src.startsWith("//", i)) {
    while (i < src.length && src[i] !== "\n") i++;
    return i;
  }
  if (src.startsWith("/*", i)) {
    let depth = 1;
    i += 2;
    while (i < src.length && depth > 0) {
      if (src.startsWith("/*", i)) {
        depth++;
        i += 2;
      } else if (src.startsWith("*/", i)) {
        depth--;
        i += 2;
      } else i++;
    }
    return i;
  }
  if (src.startsWith("r\"", i) || src.startsWith("r#", i)) {
    const hm = src.slice(i).match(/^r(#+)"/);
    if (hm) {
      const hashes = hm[1].length;
      const close = `"${"#".repeat(hashes)}`;
      const body = i + hm[0].length;
      const end = src.indexOf(close, body);
      return end < 0 ? src.length : end + close.length;
    }
  }
  const c = src[i];
  if (c === '"' || c === "'") {
    const quote = c;
    i++;
    while (i < src.length && src[i] !== quote) {
      if (src[i] === "\\") i++;
      i++;
    }
    return i + 1;
  }
  return i + 1;
}

/** Resolve `const NAME: &str = "…"` / `pub const NAME: &str = "…"` in `src`. */
function resolveStrConst(src, name) {
  const re = new RegExp(
    `(?:pub\\s+)?const\\s+${name.replace(/[$]/g, "\\$")}\\s*:\\s*&str\\s*=\\s*`,
    "g",
  );
  let m;
  while ((m = re.exec(src))) {
    const at = m.index + m[0].length;
    const s = readRustString(src, at);
    if (s !== "" || src[at] === '"' || src.startsWith('r"', at) || src.startsWith("r#", at)) {
      return s;
    }
  }
  return null;
}

/** Find `CardDef::new(` occurrences and the `;` that ends each `const`/`static`. */
function findCardDefs(src) {
  const out = [];
  const re = /CardDef::new\s*\(/g;
  let m;
  while ((m = re.exec(src))) {
    const start = m.index;
    let i = m.index + m[0].length;
    // Id: first argument is a string literal or a `const ID: &str` identifier.
    i = skipTrivia(src, i);
    let id = null;
    if (i < src.length && (src[i] === '"' || src.startsWith('r"', i) || src.startsWith("r#", i))) {
      id = readRustString(src, i);
    } else if (i < src.length && /[A-Za-z_]/.test(src[i])) {
      let j = i;
      while (j < src.length && /[A-Za-z0-9_]/.test(src[j])) j++;
      id = resolveStrConst(src, src.slice(i, j));
    }
    // Walk the `CardDef::new( … )` paren group.
    let depth = 1;
    while (i < src.length && depth > 0) {
      i = skipTrivia(src, i);
      if (i >= src.length) break;
      const c = src[i];
      if (c === "(") {
        depth++;
        i++;
      } else if (c === ")") {
        depth--;
        i++;
      } else {
        i = scanToken(src, i);
      }
    }
    // Continue over builder methods `.foo(...)` until the statement's `;`.
    while (i < src.length) {
      i = skipTrivia(src, i);
      if (src[i] === ".") {
        const dot = i;
        i++;
        while (i < src.length && /[A-Za-z0-9_]/.test(src[i])) i++;
        i = skipTrivia(src, i);
        if (src[i] === "(") {
          i++;
          let d = 1;
          while (i < src.length && d > 0) {
            i = skipTrivia(src, i);
            if (i >= src.length) break;
            if (src[i] === "(") {
              d++;
              i++;
            } else if (src[i] === ")") {
              d--;
              i++;
            } else {
              i = scanToken(src, i);
            }
          }
          continue;
        }
        i = dot;
        break;
      }
      break;
    }
    i = skipTrivia(src, i);
    const end = i; // position of `;`
    if (id == null) continue;
    out.push({ id, start, end });
  }
  return out;
}

function readRustString(src, at) {
  if (src.startsWith('r#"', at) || src.startsWith('r"', at)) {
    const hashes = src[at] === "r" && src[at + 1] === "#" ? (src.slice(at).match(/^r(#+)"/) || [])[1].length : 0;
    const openLen = 2 + hashes; // r + #* + "
    const close = `"${"#".repeat(hashes)}`;
    const bodyStart = at + openLen;
    const end = src.indexOf(close, bodyStart);
    return src.slice(bodyStart, end);
  }
  // Normal string with escapes.
  let i = at;
  if (src[i] !== '"') return "";
  i++;
  let out = "";
  while (i < src.length && src[i] !== '"') {
    if (src[i] === "\\") {
      const c = src[i + 1];
      out += c === "n" ? "\n" : c === "t" ? "\t" : c === "r" ? "\r" : c;
      i += 2;
    } else {
      out += src[i++];
    }
  }
  return out;
}

function metaCall(row) {
  const parts = [
    `        .name(${rustString(row.name)})`,
    `        .raw_name(${rustString(row.rawName ?? row.name)})`,
  ];
  if (row.derived) parts.push(`        .derived(true)`);
  parts.push(`        .tags(${rustStrArray(row.tags ?? [])})`);
  parts.push(`        .text(${rustString(row.text ?? "")})`);
  if (row.cell) parts.push(`        .cell(${rustString(row.cell)})`);
  const fields = [];
  if (row.band) fields.push(`("band", ${rustString(row.band)})`);
  if (row.owner) fields.push(`("owner", ${rustString(row.owner)})`);
  // owner is part of the card contract even when empty -- emit it explicitly
  // so the fields map mirrors the card row column.
  if (!row.owner) fields.push(`("owner", "")`);
  if (row.band) {
    // band already pushed
  }
  parts.push(`        .fields(&[${fields.join(", ")}])`);
  return `.meta(&card_sdk::meta::CardMeta::new()\n${parts.join("\n")})`;
}

function replaceMetaInFile(path, rows) {
  let src = readFileSync(path, "utf8");
  const defs = findCardDefs(src);
  // Replace from the end so offsets stay valid.
  const mine = defs.filter((d) => rows.has(d.id));
  if (!mine.length) return false;
  mine.sort((a, b) => b.start - a.start);
  let changed = false;
  for (const d of mine) {
    const row = rows.get(d.id);
    // Existing `.meta(...)` inside the builder chain (between start and end)?
    const span = src.slice(d.start, d.end);
    const metaAt = span.indexOf(".meta(");
    const call = metaCall(row);
    if (metaAt >= 0) {
      // Replace the whole `.meta(...)` call: find its parens. Token scan so
      // raw strings (`r##"…"##`, bodies may contain `"` / `"#` / parens) and
      // comments do not desync the depth counter.
      const abs = d.start + metaAt;
      let i = abs + ".meta(".length;
      let depth = 1;
      while (i < src.length && depth > 0) {
        i = skipTrivia(src, i);
        if (i >= src.length) break;
        if (src[i] === "(") {
          depth++;
          i++;
        } else if (src[i] === ")") {
          depth--;
          i++;
        } else {
          i = scanToken(src, i);
        }
      }
      const prev = src.slice(abs, i);
      if (prev === call) continue;
      src = src.slice(0, abs) + call + src.slice(i);
      changed = true;
    } else {
      // Insert before the statement's `;` at d.end.
      src = src.slice(0, d.end) + call + src.slice(d.end);
      changed = true;
    }
  }
  if (changed) writeFileSync(path, src);
  return changed;
}

