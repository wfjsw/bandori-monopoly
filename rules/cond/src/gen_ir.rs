//! Generator for the Kani-side guard IR table (`rules/kani`'s `cond_irs`).
//!
//! The table is **derived** from the guard condition strings on the `On::*`
//! entries, so it is generated at build time (`rules/kani/build.rs`) and never
//! committed: a checked-in copy drifted every time anyone edited a guard.
//! The output is a module body (no inner attributes / inner doc comments) so it
//! can be `include!`d into `rules_kani::generated::cond_irs`.
//!
//! Guard ids are stable const ids (index in the sorted, deduplicated,
//! lowerable inventory); `guard_id!("src")` resolves at compile time and an
//! unknown string is a compile error.

use std::path::Path;

use crate::lower::{lower_src, OwnedProgram};
use rules_cond_ir::nodes::{Kind, Node};

/// Generate the table from the guard inventory under `rules_dir` (the `rules/`
/// directory: `cards`, `skills`, `tiles`, `events`, `fixtures`).
/// Returns the Rust source and the number of lowered guards.
pub fn generate(rules_dir: &Path) -> (String, usize) {
    let root = rules_dir;
    let mut guards = crate::lower::inventory_guards(&root.join("cards"));
    for d in ["skills", "tiles", "events", "fixtures"] {
        for g in crate::lower::inventory_guards(&root.join(d)) {
            guards.push(g);
        }
    }
    guards.sort();
    guards.dedup();

    // First pass: which indices lower? Ids are the LOWERED subset's indices so
    // `BY_ID[id]` is total over `0..GUARD_COUNT`.
    let mut lowered: Vec<(usize, &String, OwnedProgram)> = Vec::new();
    for (i, src) in guards.iter().enumerate() {
        match lower_src(src) {
            Ok(p) => lowered.push((i, src, p)),
            Err(e) => {
                eprintln!("skip (unlowerable): {src:?}: {e}");
            }
        }
    }

    let mut out = String::new();
    out.push_str("// GENERATED by rules/kani/build.rs via `rules_cond::gen_ir::generate` (never committed).\n");
    out.push_str("// Regenerated on every build; consistency-checked by\n");
    out.push_str("// `rules/cond/tests/cond_ir_consistency.rs`.\n");
    out.push_str("//\n");
    out.push_str("// Single source of truth: the CEL condition string on each `On::*`\n");
    out.push_str("// entry. This file is the Kani-side IR of those strings.\n");
    out.push_str("//\n");
    out.push_str("// ## Guard ids\n");
    out.push_str("//\n");
    out.push_str("// `BY_ID[id]` indexes by **const id** (never a string scan).\n");
    out.push_str("// `guard_id!(\"src\")` resolves at const time; unknown strings are a\n");
    out.push_str("// compile error via `guard_id_const`.\n\n");
    out.push_str("use rules_cond_ir::nodes::{Kind, Node};\n");
    out.push_str("use rules_cond_ir::{IrCtx, Program};\n\n");
    out.push_str("/// Lowered guard programs, one per distinct inventory condition.\n");
    out.push_str("/// `SRC` is the CEL string; `PROGRAM` is its IR.\n");
    out.push_str("pub struct GuardIr {\n    pub src: &'static str,\n    pub program: Program,\n    /// Stable const id = index into [`BY_ID`].\n    pub id: usize,\n}\n\n");

    for (id, (_idx, src, prog)) in lowered.iter().enumerate() {
        let name = guard_ident(id, src);
        out.push_str(&format!("/// `{src}`\n"));
        out.push_str(&format!("/// id = {id}\n"));
        out.push_str(&format!("pub static {name}_NODES: &[Node] = &[\n"));
        for n in &prog.nodes {
            out.push_str(&format!("    {},\n", node_lit(n)));
        }
        out.push_str("];\n");
        out.push_str(&format!(
            "pub static {name}: GuardIr = GuardIr {{\n    src: \"{}\",\n    program: Program {{ nodes: {name}_NODES, root: {} }},\n    id: {id},\n}};\n\n",
            src.replace('\\', "\\\\").replace('"', "\\\""),
            prog.root
        ));
    }

    out.push_str(&format!(
        "/// Number of lowered guards. Ids are `0..GUARD_COUNT`.\npub const GUARD_COUNT: usize = {};\n\n",
        lowered.len()
    ));

    out.push_str("/// Index table: `BY_ID[id]` is the program. Ids are stable across\n");
    out.push_str("/// regeneration as long as the inventory string set is unchanged\n");
    out.push_str("/// (sorted + dedup, lowered subset, index = id).\n");
    out.push_str("pub static BY_ID: &[&GuardIr] = &[\n");
    for (id, (_idx, src, _prog)) in lowered.iter().enumerate() {
        let name = guard_ident(id, src);
        out.push_str(&format!("    &{name},\n"));
    }
    out.push_str("];\n\n");

    out.push_str("/// Every generated guard, for the consistency check.\n");
    out.push_str("pub static ALL: &[&GuardIr] = BY_ID;\n\n");

    // Compile-time string -> id: a `const fn` byte compare over `SRCS` (the
    // `guard_id!` macro lives in `rules/kani/src/generated/mod.rs`; a
    // `macro_export` macro cannot be defined by `include!`d code and then
    // used by absolute path). An unknown string is a const-eval panic, i.e. a
    // compile error.
    out.push_str("/// Every lowered guard's CEL source, indexed by guard id.\n");
    out.push_str("pub const SRCS: &[&str] = &[\n");
    for (_id, (_idx, src, _prog)) in lowered.iter().enumerate() {
        let lit = src.replace('\\', "\\\\").replace('"', "\\\"");
        out.push_str(&format!("    \"{lit}\",\n"));
    }
    out.push_str("];\n\n");
    out.push_str("/// Compile-time string -> guard id. Panics (compile error in a `const`)\n");
    out.push_str("/// on an unknown string.\n");
    out.push_str("pub const fn const_id(src: &str) -> usize {\n    let s = src.as_bytes();\n    let mut id = 0usize;\n    while id < SRCS.len() {\n        let t = SRCS[id].as_bytes();\n        if t.len() == s.len() {\n            let mut i = 0usize;\n            let mut same = true;\n            while i < s.len() {\n                if t[i] != s[i] {\n                    same = false;\n                    break;\n                }\n                i += 1;\n            }\n            if same {\n                return id;\n            }\n        }\n        id += 1;\n    }\n    panic!(\"guard_id!: unknown guard string (it has no lowering)\")\n}\n\n");

    // Runtime lookup for tests / host-side tools (NOT for Kani).
    out.push_str("/// Runtime string → id. `None` if the string is not in the inventory.\n");
    out.push_str("/// **Not** for Kani (O(n) compare). Use `guard_id!` there.\n");
    out.push_str("pub fn guard_id_opt(src: &str) -> Option<usize> {\n    let mut id = 0usize;\n    while id < GUARD_COUNT {\n        if BY_ID[id].src == src {\n            return Some(id);\n        }\n        id += 1;\n    }\n    None\n}\n\n");
    out.push_str("/// Runtime string → id. Panics on an unknown string.\n");
    out.push_str("pub fn guard_id_const(src: &str) -> usize {\n    match guard_id_opt(src) {\n        Some(id) => id,\n        None => panic!(\"guard_id!: unknown guard string; re-run gen_cond_ir\"),\n    }\n}\n\n");

    out.push_str("/// Evaluate the guard at `id` as a condition (host root rule).\n");
    out.push_str("pub fn eval_id(id: usize, ctx: &IrCtx) -> bool {\n    BY_ID[id].program.eval_bool(ctx)\n}\n\n");

    out.push_str("/// Evaluate the guard at `id`, returning the raw [`Val`].\n");
    out.push_str("pub fn eval_id_val(id: usize, ctx: &IrCtx) -> rules_cond_ir::Val {\n    BY_ID[id].program.eval(ctx)\n}\n");
    (out, lowered.len())
}

fn guard_ident(i: usize, src: &str) -> String {
    // Stable name from a short hash of the source.
    let mut h: u64 = 0xcbf2_9ce4_8422_2325;
    for b in src.as_bytes() {
        h ^= *b as u64;
        h = h.wrapping_mul(0x0000_0100_0000_01b3);
    }
    format!("G_{:04x}_{:016x}", i, h)
}

fn node_lit(n: &Node) -> String {
    let k = match n.kind {
        Kind::ConstInt => "Kind::ConstInt",
        Kind::ConstBool => "Kind::ConstBool",
        Kind::ConstNull => "Kind::ConstNull",
        Kind::Var => "Kind::Var",
        Kind::Neg => "Kind::Neg",
        Kind::Not => "Kind::Not",
        Kind::And => "Kind::And",
        Kind::Or => "Kind::Or",
        Kind::Tern => "Kind::Tern",
        Kind::Add => "Kind::Add",
        Kind::Sub => "Kind::Sub",
        Kind::Mul => "Kind::Mul",
        Kind::Div => "Kind::Div",
        Kind::Rem => "Kind::Rem",
        Kind::Eq => "Kind::Eq",
        Kind::Ne => "Kind::Ne",
        Kind::Lt => "Kind::Lt",
        Kind::Le => "Kind::Le",
        Kind::Gt => "Kind::Gt",
        Kind::Ge => "Kind::Ge",
        Kind::In => "Kind::In",
        Kind::Size => "Kind::Size",
        Kind::List => "Kind::List",
        Kind::Call => "Kind::Call",
    };
    format!(
        "Node {{ kind: {k}, payload: {}, a: {}, b: {}, c: {} }}",
        n.payload, n.a, n.b, n.c
    )
}
